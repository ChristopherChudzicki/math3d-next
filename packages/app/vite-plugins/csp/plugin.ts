import { appendFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";
import type { Plugin } from "vite";

type PolicyInputs = {
  apiBaseUrl: string;
  sentryDsn?: string;
  release?: string;
};

/** Sentry's endpoint for browser security reports, from a project DSN. */
const sentrySecurityEndpoint = (dsn: string, release?: string): string => {
  const url = new URL(dsn);
  const projectId = url.pathname.slice(1);
  const params = new URLSearchParams({
    sentry_key: url.username,
    sentry_environment: "production",
  });
  if (release) params.set("sentry_release", release);
  return `${url.origin}/api/${projectId}/security/?${params}`;
};

/**
 * The app's Content-Security-Policy and reporting headers. Embedding is a
 * supported feature, as it was in math3d-react, so the policy sets no
 * `frame-ancestors`; a cross-site embed is signed out because the session
 * cookie is SameSite=Lax.
 */
export const securityHeaders = ({
  apiBaseUrl,
  sentryDsn,
  release,
}: PolicyInputs): Record<string, string> => {
  const connect = ["'self'", new URL(apiBaseUrl).origin];
  if (sentryDsn) connect.push(new URL(sentryDsn).origin);
  const directives = [
    "default-src 'self'",
    // Cloudflare Web Analytics injects its beacon script at the edge; the
    // beacon reports to the same origin.
    "script-src 'self' https://static.cloudflareinsights.com 'report-sample'",
    // MathLive writes `<style>` elements and inline `style` attributes.
    "style-src 'self' 'unsafe-inline'",
    // The backend builds scene thumbnail URLs from its own screenshots-Worker
    // origin; allowing any https host avoids repeating that config here.
    "img-src 'self' data: https:",
    "font-src 'self' data:",
    `connect-src ${connect.join(" ")}`,
    "object-src 'none'",
    "base-uri 'self'",
    // No `form-action`: Chrome applies it to each redirect after sign-in's
    // POST, a chain through Google's pages that we don't control.
  ];
  if (!sentryDsn) {
    return { "Content-Security-Policy": directives.join("; ") };
  }
  const endpoint = sentrySecurityEndpoint(sentryDsn, release);
  // Browsers that support `report-to` ignore `report-uri`.
  directives.push(`report-uri ${endpoint}`, "report-to csp-endpoint");
  return {
    "Content-Security-Policy": directives.join("; "),
    "Reporting-Endpoints": `csp-endpoint="${endpoint}"`,
  };
};

const BLOCK_MARKER = "# Generated by vite-plugins/csp";

/** A `_headers` rule applying `headers` to every path. */
export const headersRule = (headers: Record<string, string>): string =>
  [
    BLOCK_MARKER,
    "/*",
    ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`),
  ].join("\n");

/** The headers in the rule `headersRule` wrote into a `_headers` file. */
export const parseHeadersRule = (file: string): Record<string, string> => {
  const start = file.indexOf(BLOCK_MARKER);
  if (start === -1) return {};
  const lines = file.slice(start).split("\n").slice(2);
  const end = lines.findIndex((line) => !line.startsWith("  "));
  return Object.fromEntries(
    lines.slice(0, end === -1 ? undefined : end).map((line) => {
      const [name, ...value] = line.trim().split(": ");
      return [name, value.join(": ")];
    }),
  );
};

/**
 * Appends the headers to the build's `_headers`, which Cloudflare applies to
 * every asset response, including those the OG Worker passes through.
 * `vite preview` sends this rule back from that file, so E2E tests what the
 * build wrote. The dev server gets none: React Fast Refresh runs an inline
 * script.
 */
export const csp = (): Plugin => {
  let headersFile = "";
  let headers: Record<string, string> = {};
  return {
    name: "math3d:csp",
    apply: (_config, env) => env.command === "build" || !!env.isPreview,
    configResolved(config) {
      headersFile = path.resolve(config.root, config.build.outDir, "_headers");
      headers = securityHeaders({
        apiBaseUrl: config.env.VITE_API_BASE_URL,
        sentryDsn: config.env.VITE_SENTRY_DSN,
        release: config.env.VITE_APP_VERSION,
      });
    },
    // Vite copies `public/_headers` into the build before this runs.
    writeBundle() {
      appendFileSync(headersFile, `\n${headersRule(headers)}\n`);
    },
    configurePreviewServer(server) {
      const built = existsSync(headersFile)
        ? parseHeadersRule(readFileSync(headersFile, "utf8"))
        : {};
      server.middlewares.use((_req, res, next) => {
        Object.entries(built).forEach(([name, value]) =>
          res.setHeader(name, value),
        );
        next();
      });
    },
  };
};
